<h3 class=""> Our Objective</h3>
<p>At <strong>JDS Public School</strong> we strongly believe and it is our prime objective to inculcate the following in our teaching philosophy:
</p>

<ul>
  <li>&bull; Learning must take place at home, in school and in the community.</li>
  <li>&bull; Learning is an important aspect of each person&rsquo;s existence</li>
  <li>&bull; Learning is a lifelong process.</li>
  <li>&bull; We must provide educational opportunities from school readiness through adult education.</li>
  <li>&bull; Everyone is accountable for improving student achievement.</li>
  <li>&bull; All students will learn when their individual needs are met.</li>
  <li>&bull; Teaching all students how to learn is essential.</li>
  <li>&bull; We must prepare all students for a knowledge-based, technologically rich and culturally diverse future.</li>
  <li>&bull; We must provide a safe and secure environment, which is essential for teaching and learning.</li>
  <li>&bull; Stakeholder involvement, which includes partnerships with parents, community, businesses and governmental agencies, which enhances student achievement.</li>
  <li>&bull; We must treat all individuals with respect and dignity.</li>
  <li>&bull; Stakeholder involvement and input are valuable tools for decision-making.</li>
  <li>&bull; We must promote cultural diversity and the reinforcement of positive character education.</li>
  <li>&bull; Responsible citizens are the foundation of a democratic society.</li>
</ul>
